
BEGIN;

-- =========================================================
-- 1. NOTIFICATIONS TABLE
-- =========================================================

CREATE TABLE public.notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES public.profiles(id)
        ON DELETE CASCADE,

    actor_id UUID
        REFERENCES public.profiles(id)
        ON DELETE SET NULL,

    type TEXT NOT NULL,

    title TEXT NOT NULL,

    message TEXT NOT NULL,

    action_url TEXT,

    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,

    dedupe_key TEXT,

    read_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT notifications_type_check
        CHECK (
            type IN (
                'system',
                'article',
                'comment',
                'moderation',
                'account',
                'security',
                'announcement'
            )
        ),

    CONSTRAINT notifications_title_length_check
        CHECK (
            char_length(BTRIM(title)) BETWEEN 1 AND 160
        ),

    CONSTRAINT notifications_message_length_check
        CHECK (
            char_length(BTRIM(message)) BETWEEN 1 AND 2000
        ),

    CONSTRAINT notifications_action_url_check
        CHECK (
            action_url IS NULL
            OR (
                char_length(action_url) BETWEEN 1 AND 2048
                AND LEFT(action_url, 1) = '/'
                AND LEFT(action_url, 2) <> '//'
                AND POSITION(E'\\' IN action_url) = 0
            )
        ),

    CONSTRAINT notifications_metadata_object_check
        CHECK (
            jsonb_typeof(metadata) = 'object'
        ),

    CONSTRAINT notifications_dedupe_key_length_check
        CHECK (
            dedupe_key IS NULL
            OR char_length(dedupe_key) BETWEEN 1 AND 200
        )
);

COMMENT ON TABLE public.notifications IS
    'Private, user-specific in-app notifications generated by trusted server-side application events.';

COMMENT ON COLUMN public.notifications.user_id IS
    'The user who receives this notification.';

COMMENT ON COLUMN public.notifications.actor_id IS
    'Optional user responsible for triggering the notification.';

COMMENT ON COLUMN public.notifications.type IS
    'Notification category: system, article, comment, moderation, account, security, or announcement.';

COMMENT ON COLUMN public.notifications.action_url IS
    'Optional same-site relative path for the notification action.';

COMMENT ON COLUMN public.notifications.metadata IS
    'Optional structured event context. Must be a JSON object.';

COMMENT ON COLUMN public.notifications.dedupe_key IS
    'Optional event idempotency key unique per recipient.';

COMMENT ON COLUMN public.notifications.read_at IS
    'NULL means unread; a timestamp means the notification has been read.';


-- =========================================================
-- 2. INDEXES
-- =========================================================

-- Efficient newest-first notification listing.
CREATE INDEX notifications_user_created_cursor_idx
    ON public.notifications (
        user_id,
        created_at DESC,
        id DESC
    );

-- Efficient unread count and unread listing.
CREATE INDEX notifications_user_unread_cursor_idx
    ON public.notifications (
        user_id,
        created_at DESC,
        id DESC
    )
    WHERE read_at IS NULL;

-- Prevent duplicate event notifications for the same recipient.
CREATE UNIQUE INDEX notifications_user_dedupe_key_uidx
    ON public.notifications (user_id, dedupe_key)
    WHERE dedupe_key IS NOT NULL;


-- =========================================================
-- 3. PROTECT NOTIFICATION CONTENT
-- =========================================================

CREATE OR REPLACE FUNCTION public.protect_notification_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
    -- Only read_at may be changed by the recipient.
    -- actor_id may additionally be cleared by ON DELETE SET NULL.
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR (
           NEW.actor_id IS DISTINCT FROM OLD.actor_id
           AND NOT (
               OLD.actor_id IS NOT NULL
               AND NEW.actor_id IS NULL
           )
       )
       OR NEW.type IS DISTINCT FROM OLD.type
       OR NEW.title IS DISTINCT FROM OLD.title
       OR NEW.message IS DISTINCT FROM OLD.message
       OR NEW.action_url IS DISTINCT FROM OLD.action_url
       OR NEW.metadata IS DISTINCT FROM OLD.metadata
       OR NEW.dedupe_key IS DISTINCT FROM OLD.dedupe_key
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN

        RAISE EXCEPTION 'Notification content cannot be modified.'
            USING ERRCODE = '42501';
    END IF;

    -- The database controls the actual read timestamp.
    IF NEW.read_at IS DISTINCT FROM OLD.read_at THEN
        NEW.read_at := CASE
            WHEN NEW.read_at IS NULL THEN NULL
            ELSE NOW()
        END;
    END IF;

    RETURN NEW;
END;
$function$;

CREATE TRIGGER notifications_protect_update
    BEFORE UPDATE ON public.notifications
    FOR EACH ROW
    EXECUTE FUNCTION public.protect_notification_update();

REVOKE ALL ON FUNCTION public.protect_notification_update()
    FROM PUBLIC, anon, authenticated;


    GRANT EXECUTE ON FUNCTION public.protect_notification_update()
    TO service_role;


-- =========================================================
-- 4. ROW LEVEL SECURITY
-- =========================================================

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Users can only read their own notifications.
CREATE POLICY notifications_select_own
    ON public.notifications
    FOR SELECT
    TO authenticated
    USING (
        user_id = (SELECT auth.uid())
    );

-- Users can only update their own notifications.
-- The trigger independently protects all content fields.
CREATE POLICY notifications_update_own
    ON public.notifications
    FOR UPDATE
    TO authenticated
    USING (
        user_id = (SELECT auth.uid())
    )
    WITH CHECK (
        user_id = (SELECT auth.uid())
    );

-- Users can only delete their own notifications.
CREATE POLICY notifications_delete_own
    ON public.notifications
    FOR DELETE
    TO authenticated
    USING (
        user_id = (SELECT auth.uid())
    );

-- Deliberately no INSERT policy for authenticated users.


-- =========================================================
-- 5. TABLE PRIVILEGES
-- =========================================================

REVOKE ALL ON TABLE public.notifications
    FROM PUBLIC, anon, authenticated;

GRANT SELECT, UPDATE, DELETE
    ON TABLE public.notifications
    TO authenticated;

GRANT DELETE, INSERT, REFERENCES, SELECT, TRIGGER, TRUNCATE, UPDATE
    ON TABLE public.notifications
    TO service_role;


COMMIT;
